/**
 * Orders strings by UTF-16 code unit, independent of locale, so that results
 * are stable and match SQLite's default BINARY collation for ASCII values.
 */
export function compareCodeUnits(a: string, b: string): number {
  if (a < b) {
    return -1;
  }
  return a > b ? 1 : 0;
}
